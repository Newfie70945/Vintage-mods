using System;
using System.Linq;
using BlockLogger.Frontend;
using NewfiesCommunityMOTD;
int checks = 0;
void Check(bool value, string message) { checks++; if (!value) throw new Exception(message); }
var names = AdminPlayerChoices.Create(new[] { ("account-2", "Lorreth"), ("account-1", "Lorreth"), ("account-1", "Other"), ("", "bad") });
Check(names.Values.SequenceEqual(new[]{"account-1", "account-2"}), "Actions use distinct UIDs even when roleplay names match");
Check(names.Labels.Distinct().Count() == 2, "Duplicate display names remain distinguishable");
Check(names.Values.All(x => x != "Lorreth"), "Display aliases never become action targets");
Check(AdminPlayerChoices.Create(Array.Empty<(string,string)>()).Values.Single() == "", "Empty picker sentinel");
Check(AdminPlayerChoices.Create(new[]{("uid", "")}).Labels.Single() == "uid", "Empty display-name fallback");
var renamed = AdminPlayerChoices.Create(new[]{("account-1", "New RP name")});
Check(renamed.Values.Single() == "account-1", "Renaming does not change target identity");
string local = "<font size=\"17\"><strong>Owner title</strong></font>\r\nOwner text[br]- Item";
var item = new MotdFeedItem { Id="discord-123", Title="<unsafe> & title", Author="<author>", BodyVtml="<strong>Kept markup</strong>\r\nNext line", UnixTime=1704067200, Url="https://discord.com/channels/a?x=1&y=2", Important=true };
string Build(string? l, bool use=true, int limit=10, string accent="#D9B777", bool merge=true) => MotdFeedFormatter.Build("Updates", l, use, new[]{item}, limit, accent, merge);
var feed=Build(local);
Check(feed.Contains("Owner title") && !feed.Contains("Server Update"), "Do not duplicate owner headings");
Check(feed.Contains("&lt;unsafe&gt; &amp; title"), "Remote titles are escaped");
Check(feed.Contains("&lt;author&gt;"), "Remote authors are escaped");
Check(feed.Contains("<strong>Kept markup</strong>"), "Body VTML is preserved");
Check(feed.Contains("[[MOTDNEW:discord-123]]"), "Unread IDs survive formatting");
Check(feed.Contains("IMPORTANT"), "Important marker survives");
Check(feed.Contains("01 Jan 2024") && feed.Contains("UTC"), "Dates carry explicit timezone");
Check(!feed.Contains('\r') && !feed.Contains("[br]"), "All line endings normalize");
Check(Build(local,merge:false).Contains("Kept markup") && !Build(local,merge:false).Contains("Owner title"), "Remote replacement honors merge setting");
Check(Build(local,use:false,merge:false).Contains("Owner title"), "Local fallback when remote feed is disabled");
Check(!Build(null,use:false).Contains("[[MOTDNEW:"), "Disabled remote has no unread markers");
Check(Build(null,use:false).Contains("No updates"), "Empty feed has useful text");
Check(!Build(null,accent:"red\" size=\"999").Contains("999"), "Invalid accent cannot inject VTML");
item.Url="javascript:alert(1)";
Check(!Build(null).Contains("href="), "Unsafe URL scheme is rejected");
item.UnixTime=long.MaxValue;
Check(Build(null).Contains("Kept markup"), "Invalid date does not hide a post");
var many = Enumerable.Range(0,70).Select(i => new MotdFeedItem{Title="p"+i,Id="id-"+i}).ToArray();
var limited = MotdFeedFormatter.Build("News",null,true,many,999,null,true);
Check(limited.Contains("[[MOTDNEW:id-49]]") && !limited.Contains("[[MOTDNEW:id-50]]"), "Hard feed-item cap retained");
Console.WriteLine($"{checks} checks passed");
